"""Build the three contrastive-embedder evaluation slices.

These are generated **once**, before training, and held fixed across
all epochs / runs / hyperparameter sweeps. The slice-3 metric is the
load-bearing go/no-go signal for Stage 2c.

Slices:

  1. data/sim_eval_synthetic.parquet
     5k (anchor, positive) pairs from a held-out set of anchors,
     generated by perturb.py with a fixed seed. Sanity check —
     model should crush this. Anchors are pulled from the test
     bucket of `sim_anchors.parquet` so the trainer has never seen
     them.

  2. data/sim_eval_levenshtein_replay.parquet
     5k production labels. For each, runs the **current**
     `pg_trgm + levenshtein` query against PG and captures its
     top-5 result. Eval question: does the new ANN top-5 contain
     >=4 of the levenshtein top-5? Floor metric — "don't regress".

  3. data/sim_eval_pg_trgm_misses.parquet
     ~200 manually-curated pairs that pg_trgm currently drops.
     Real homoglyph / lookalike / typosquat-class neighbors with
     low trigram overlap. recall@5 here is the load-bearing
     metric — pg_trgm fails this slice today by design.

Schema (consistent across all three for downstream eval code):
    columns:
        anchor: str           # query label
        targets: list[str]    # one or more "should be in top-K" labels
        slice: str            # "synthetic" | "lev_replay" | "pg_trgm_miss"
        notes: str            # free-text provenance ("homoglyph m->rn" etc.)

Run:
    uv run ml/build_sim_eval.py
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import psycopg2

sys.path.insert(0, str(Path(__file__).parent))

import perturb  # noqa: E402

ML_DIR = Path(__file__).parent
DATA_DIR = ML_DIR / "data"

DEFAULT_PG_URL = (
    "dbname=nameserver user=nameserver_admin host=localhost port=5433 sslmode=disable"
)


# -- Slice 1: synthetic ------------------------------------------------------


def build_synthetic_slice(
    anchors_df: pd.DataFrame, n: int, seed: int,
) -> pd.DataFrame:
    """Pick `n` test-bucket anchors and generate one perturbation each."""
    rng = random.Random(seed)
    test_anchors = anchors_df.loc[anchors_df["bucket"] == "test", "label"].tolist()
    if len(test_anchors) < n:
        print(f"[warn] only {len(test_anchors):,} test anchors available, "
              f"requested {n:,}", flush=True)
        n = len(test_anchors)
    rng.shuffle(test_anchors)
    rows: list[dict[str, object]] = []
    used: set[str] = set()
    for anchor in test_anchors:
        if len(rows) >= n:
            break
        if anchor in used:
            continue
        try:
            result = perturb.generate(anchor, rng)
        except perturb.PerturbError:
            continue
        used.add(anchor)
        rows.append({
            "anchor": result.label,         # query is the *perturbed* label
            "targets": [anchor],            # ground truth is the original
            "slice": "synthetic",
            "notes": f"perturb:{result.strategy}",
        })
    return pd.DataFrame(rows)


# -- Slice 2: levenshtein replay --------------------------------------------


def build_levenshtein_replay_slice(
    pg_url: str, anchors_df: pd.DataFrame, n: int, seed: int,
) -> pd.DataFrame:
    """For `n` random labels, capture the current production tier-2 result.

    Mirrors the SQL in `crates/nameserver-control/src/similarity.rs`
    `search_edit_distance(label, max_distance=2)` so the captured
    targets are *exactly* what production returns today.
    """
    rng = random.Random(seed)
    test_anchors = anchors_df.loc[anchors_df["bucket"] == "test", "label"].tolist()
    rng.shuffle(test_anchors)

    rows: list[dict[str, object]] = []
    with psycopg2.connect(pg_url) as conn:
        with conn.cursor() as cur:
            for anchor in test_anchors:
                if len(rows) >= n:
                    break
                if len(anchor) < 4:
                    continue
                cur.execute(
                    """
                    SELECT sub.label
                      FROM (
                        SELECT e.label,
                               levenshtein(e.label, %s) AS dist
                          FROM domain_label_embeddings e
                         WHERE e.label <> %s
                           AND e.label %% %s
                           AND length(e.label)
                               BETWEEN length(%s) - 2 AND length(%s) + 2
                      ) sub
                     WHERE sub.dist BETWEEN 1 AND 2
                     ORDER BY sub.dist ASC
                     LIMIT 5
                    """,
                    (anchor, anchor, anchor, anchor, anchor),
                )
                targets = [r[0] for r in cur.fetchall()]
                if not targets:
                    continue  # skip queries with no neighbors — uninformative
                rows.append({
                    "anchor": anchor,
                    "targets": targets,
                    "slice": "lev_replay",
                    "notes": f"production tier-2 top-{len(targets)}",
                })
    return pd.DataFrame(rows)


# -- Slice 3: pg_trgm misses (curated) --------------------------------------


# Curated pairs: cases where the contrastive embedder must succeed
# precisely because pg_trgm + levenshtein fails them today, OR where
# levenshtein technically succeeds but the pair is the canonical
# example we want documented.
#
# Each row: (anchor, [targets], notes). The anchor is the *query* the
# embedder will be asked about; targets are labels we expect in top-5.
CURATED_PAIRS: list[tuple[str, list[str], str]] = [
    # --- homoglyph rn<->m (drops out of pg_trgm @ threshold 0.3) ---------
    ("arnazon",       ["amazon"],    "homoglyph m->rn"),
    ("rnicrosoft",    ["microsoft"], "homoglyph m->rn at start"),
    ("googlernail",   ["googlemail"], "homoglyph m->rn mid"),
    ("face600k",      ["facebook"],  "edge: high-trigram-divergence neighbor"),

    # --- digit/letter homoglyphs (low trigram overlap) -------------------
    ("g00gle",        ["google"],    "homoglyph 0<->o, double substitution"),
    ("paypa1",        ["paypal"],    "homoglyph l->1 final pos"),
    ("amaz0n",        ["amazon"],    "homoglyph o->0 mid"),
    ("micr0soft",     ["microsoft"], "homoglyph o->0 mid"),
    ("c1tibank",      ["citibank"],  "homoglyph i->1 second pos"),
    ("netf1ix",       ["netflix"],   "homoglyph l->1"),
    ("rea1tor",       ["realtor"],   "homoglyph l->1 mid"),
    ("appie",         ["apple"],     "homoglyph l->i (single sub, lookalike)"),
    ("twitber",       ["twitter"],   "homoglyph t->b speculative"),

    # --- ascii lookalikes that pg_trgm sometimes drops -------------------
    ("paypaal",       ["paypal"],    "double-letter typosquat (insert)"),
    ("googel",        ["google"],    "adjacent swap"),
    ("amaozn",        ["amazon"],    "adjacent swap"),
    ("yahooo",        ["yahoo"],     "tail double letter"),
    ("linkedln",      ["linkedin"],  "homoglyph i->l (single sub)"),
    ("tvvitter",      ["twitter"],   "homoglyph w->vv at start"),

    # --- legit defensive registrations (should still surface) ------------
    ("googie",        ["google"],    "real google defensive registration"),
    ("goggle",        ["google"],    "real other brand, edit dist 1"),
    ("amzon",         ["amazon"],    "missing letter, common typosquat"),
    ("amazn",         ["amazon"],    "missing letter mid"),

    # --- moodle/google class — very low trigram overlap ------------------
    ("moodle",        ["google"],    "load-bearing pg_trgm-miss case"),
    ("noogle",        ["google"],    "single sub at start, low overlap"),
    ("doodle",        ["google"],    "single sub at start"),

    # --- Korean phishing impersonation patterns (project-relevant) -------
    ("naverr",        ["naver"],     "double letter (Korean portal)"),
    ("kak4o",         ["kakao"],     "homoglyph a->4"),
    ("kak0",          ["kakao"],     "deletion + homoglyph"),
    ("nateqo",        ["nate"],      "insert + extension"),

    # --- bank / fintech impersonation surface ----------------------------
    ("ban-kof-america", ["bankofamerica"], "hyphen insertion"),
    ("paypall",       ["paypal"],    "trailing double letter"),
    ("chasebanc",     ["chasebank"], "tail substitution"),
    ("we1lsfargo",    ["wellsfargo"], "homoglyph l->1"),

    # --- defensive: common subdomain labels should NOT be 'similar' ------
    # These are anchors where we want the embedder to *not* surface
    # unrelated co-located labels. Targets list here is intentional —
    # a CDN subdomain like "static" is a lexical neighbor of nothing.
    # We leave these out of the curated set and rely on the negative
    # mining in training to handle them; revisit if eval shows FPs.
]


def build_pg_trgm_miss_slice() -> pd.DataFrame:
    """Materialize the curated pair list as the eval slice."""
    rows: list[dict[str, object]] = []
    for anchor, targets, notes in CURATED_PAIRS:
        # Anchors must be DNS-legal so the encoder can ingest them at
        # inference time. Validate before writing.
        if not perturb.is_dns_legal(anchor):
            print(f"[err] curated anchor {anchor!r} is not DNS-legal — skipping",
                  flush=True, file=sys.stderr)
            continue
        for t in targets:
            if not perturb.is_dns_legal(t):
                print(f"[err] curated target {t!r} not DNS-legal — skipping",
                      flush=True, file=sys.stderr)
                break
        else:
            rows.append({
                "anchor": anchor,
                "targets": list(targets),
                "slice": "pg_trgm_miss",
                "notes": notes,
            })
    return pd.DataFrame(rows)


# -- Main --------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--anchors", type=Path, default=DATA_DIR / "sim_anchors.parquet",
    )
    parser.add_argument("--out-dir", type=Path, default=DATA_DIR)
    parser.add_argument("--n-synthetic", type=int, default=5_000)
    parser.add_argument("--n-lev-replay", type=int, default=5_000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    pg_url = os.environ.get("PGURL", DEFAULT_PG_URL)

    if not args.anchors.exists():
        print(f"[err] anchors not found at {args.anchors} — "
              f"run build_sim_anchors.py first", flush=True, file=sys.stderr)
        return 1

    anchors_df = pd.read_parquet(args.anchors)
    print(f"[anchors] {len(anchors_df):,} loaded "
          f"(test={len(anchors_df[anchors_df['bucket'] == 'test']):,})", flush=True)

    # Slice 1
    print("[slice1] building synthetic eval...", flush=True)
    syn_df = build_synthetic_slice(anchors_df, args.n_synthetic, args.seed)
    syn_path = args.out_dir / "sim_eval_synthetic.parquet"
    syn_df.to_parquet(syn_path, index=False)
    print(f"[slice1] -> {syn_path} ({len(syn_df):,} rows)", flush=True)

    # Slice 2
    print("[slice2] replaying production levenshtein query...", flush=True)
    lev_df = build_levenshtein_replay_slice(
        pg_url, anchors_df, args.n_lev_replay, args.seed,
    )
    lev_path = args.out_dir / "sim_eval_levenshtein_replay.parquet"
    lev_df.to_parquet(lev_path, index=False)
    print(f"[slice2] -> {lev_path} ({len(lev_df):,} rows)", flush=True)

    # Slice 3
    print("[slice3] materializing curated pg_trgm-miss pairs...", flush=True)
    miss_df = build_pg_trgm_miss_slice()
    miss_path = args.out_dir / "sim_eval_pg_trgm_misses.parquet"
    miss_df.to_parquet(miss_path, index=False)
    print(f"[slice3] -> {miss_path} ({len(miss_df):,} rows)", flush=True)

    # Combined manifest for downstream eval code
    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "seed": args.seed,
        "slices": {
            "synthetic": {
                "path": str(syn_path),
                "rows": len(syn_df),
                "metric": "recall@5",
                "expected_target": ">=0.95 (sanity)",
            },
            "lev_replay": {
                "path": str(lev_path),
                "rows": len(lev_df),
                "metric": "top5_overlap_with_levenshtein",
                "expected_target": ">=0.80 (don't regress on what we have today)",
            },
            "pg_trgm_miss": {
                "path": str(miss_path),
                "rows": len(miss_df),
                "metric": "recall@5",
                "expected_target": ">=0.85 (load-bearing for go/no-go)",
            },
        },
    }
    manifest_path = args.out_dir / "sim_eval.manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2))
    print(f"[manifest] -> {manifest_path}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
